def _score_word(n: int) -> str:
    if 11 <= n % 100 <= 14:
        return "баллов"
    last = n % 10
    if last == 1:
        return "балл"
    if 2 <= last <= 4:
        return "балла"
    return "баллов"


def _format_criteria(tiers: list[tuple[int, str]]) -> str:
    """Собирает HTML для explanation — по одному <p> на каждый уровень
    баллов, в том же виде, что и на вашем скрине с критериями."""
    lines = []
    for points, text in tiers:
        lines.append(f"<p><b>{points} {_score_word(points)}:</b> {text}</p>")
    return "\n".join(lines)


async def main():
    async with async_session() as session:
        for (subject_slug, task_number), tiers in CRITERIA_BY_TASK_NUMBER.items():
            subject = (
                await session.execute(select(Subject).where(Subject.slug == subject_slug))
            ).scalar_one_or_none()
            if subject is None:
                print(f"⚠ предмет не найден: {subject_slug}")
                continue

            explanation_html = _format_criteria(tiers)

            result = await session.execute(
                update(Task)
                .where(
                    Task.subject_id == subject.id,
                    Task.task_number == task_number,
                    Task.part == 2,  # защита: не трогаем часть 1 с тем же номером
                )
                .values(criteria=explanation_html)
            )
            if result.rowcount == 0:
                print(f"⚠ ничего не обновлено: {subject_slug} №{task_number} "
                      f"(нет заданий part=2 с таким номером в БД)")
            else:
                print(f"{subject_slug} №{task_number}: обновлено строк = {result.rowcount}")

        await session.commit()
    print("Готово.")


asyncio.run(main())