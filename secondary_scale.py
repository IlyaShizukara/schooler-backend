# Математика базовая (ОГЭ-подобная логика для ЕГЭ база) переводится не в
# баллы 0-100, а в ОЦЕНКУ 2..5 — отдельная таблица, отдельная логика показа
# на фронте ("Оценка: 4", а не "78 баллов").
MATH_BASIC_GRADE_SCALE: list[tuple[int, int, int]] = [
    # (мин_первичный, макс_первичный, оценка)
    (0, 6, 2),
    (7, 11, 3),
    (12, 16, 4),
    (17, 21, 5),
]


def get_secondary_score(subject_slug: str, primary_score: int) -> int | None:
    """Первичный -> тестовый балл (0-100). None, если для предмета нет
    такой шкалы (например math_basic — см. get_math_basic_grade) или
    предмета вообще нет в таблице (китайский, немецкий и т.п. — не
    добавлены, т.к. этих предметов нет в приложении)."""
    scale = SECONDARY_SCALE.get(subject_slug)
    if scale is None:
        return None
    if primary_score in scale:
        return scale[primary_score]
    # На случай, если earned_points каким-то образом превысит максимум
    # таблицы (не должно происходить при корректных Task.points, но на
    # всякий случай не даём upstream-ошибке уронить эндпоинт) — берём
    # ближайшее не большее значение.
    keys = sorted(k for k in scale if k <= primary_score)
    return scale[keys[-1]] if keys else 0


def get_math_basic_grade(primary_score: int) -> int:
    """Первичный балл базовой математики -> оценка 2..5."""
    for lo, hi, grade in MATH_BASIC_GRADE_SCALE:
        if lo <= primary_score <= hi:
            return grade
    return 5 if primary_score > MATH_BASIC_GRADE_SCALE[-1][1] else 2